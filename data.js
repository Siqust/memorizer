function parseWords(text, page) {
  return text.trim().split('\n').map(line => {
    const [w, rel = ''] = line.split('|').map(s => s.trim());
    return { id: w.replace(/[\[\]]/g, ''), pattern: w, related: rel, page };
  });
}

